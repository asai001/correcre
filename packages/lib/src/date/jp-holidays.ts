export const JP_HOLIDAY_NAMES: ReadonlyMap<string, string> = new Map(JP_HOLIDAY_ENTRIES);

const JP_HOLIDAY_SET: ReadonlySet<string> = new Set(JP_HOLIDAY_ENTRIES.map(([date]) => date));

export function isJpHoliday(date: string): boolean {
  return JP_HOLIDAY_SET.has(date);
}

export function getJpHolidayName(date: string): string | undefined {
  return JP_HOLIDAY_NAMES.get(date);
}
